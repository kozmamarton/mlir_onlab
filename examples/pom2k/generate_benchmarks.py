#!/usr/bin/env python3
"""Generates the per-kernel differential benchmarks under examples/pom2k.

For every kernel it reads the pipeline outputs without the custom fusion pass
(src/loop_fusion/pom2k/compare/old) and with it (.../compare/new), and writes
into the kernel's directory:
  diff_cpu_parallel.cpp   harness running both variants on identical inputs,
                          comparing every array bitwise and timing both
  run_diff_benchmark.sh   thin wrapper around lib/run_diff_kernel.sh

Kernels without a function (empty inputs) are reported and skipped.
"""

import argparse
import hashlib
import pathlib
import re
import sys

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent
COMPARE_DIR = PROJECT_ROOT / "src" / "loop_fusion" / "pom2k" / "compare"

# Existing directories that do not follow the pom2k_<name> convention.
DIR_OVERRIDES = {"ext_add_ad_2d_": "pom2k_ext_add_ad_2d"}

# Fixed configuration of the integer inputs that select branches.
SELECTOR_ARRAYS = {"iext": 1, "isplit": 30, "nbc": 1}
FIXED_INT_GLOBALS = {"mode": 3, "ntp": 2}
# Integer globals derived from the problem size (C expressions in the harness).
SIZE_INT_GLOBALS = {
    "im": "cfg.im", "jm": "cfg.jm", "kb": "cfg.kb",
    "imm1": "cfg.im - 1", "jmm1": "cfg.jm - 1", "kbm1": "cfg.kb - 1",
    "imm2": "cfg.im - 2", "jmm2": "cfg.jm - 2", "kbm2": "cfg.kb - 2",
}


def kernel_dir(kernel):
    if kernel in DIR_OVERRIDES:
        return SCRIPT_DIR / DIR_OVERRIDES[kernel]
    name = kernel[len("ext_"):] if kernel.startswith("ext_") else kernel
    return SCRIPT_DIR / ("pom2k_" + name.rstrip("_"))


def seed_of(*parts):
    return int.from_bytes(hashlib.sha256("/".join(parts).encode()).digest()[:8],
                          "little")


def split_top_level(text):
    """Splits on commas that are not nested in (), <>, {}, [] or quotes."""
    parts, depth, cur, quoted = [], 0, [], False
    for ch in text:
        if ch == '"':
            quoted = not quoted
        elif not quoted:
            if ch in "(<{[":
                depth += 1
            elif ch in ")>}]":
                depth -= 1
            elif ch == "," and depth == 0:
                parts.append("".join(cur))
                cur = []
                continue
        cur.append(ch)
    if "".join(cur).strip():
        parts.append("".join(cur))
    return parts


def parse_signature(text, kernel):
    start = text.find(f"func.func @{kernel}(")
    if start < 0:
        return None
    i = text.index("(", start) + 1
    depth, j = 1, i
    while depth:
        if text[j] == "(":
            depth += 1
        elif text[j] == ")":
            depth -= 1
        j += 1
    args = []
    for raw in split_top_level(text[i:j - 1]):
        m = re.match(r'\s*%arg(\d+):\s*memref<\?x(f32|i32)>', raw)
        if not m:
            raise ValueError(f"{kernel}: unsupported argument '{raw.strip()}'")
        name = re.search(r'polygeist\.name = "(\w+)"', raw)
        args.append({"index": int(m.group(1)), "elem": m.group(2),
                     "name": name.group(1) if name else f"arg{m.group(1)}"})
    return args


def parse_globals(text):
    found = {}
    for name, elem in re.findall(
            r'memref\.global (?:"private" )?(?:constant )?@(\w+) : memref<1x(f32|i32)>',
            text):
        found[name] = elem
    return found


def three_d_args(text):
    """Arguments that need im*jm*kb elements: accessed through a rank-3 view,
    accessed directly, or never through a view. Rank-2-only arguments get
    im*jm; the harness guard pages catch an access past that."""
    views = {}
    for arg, sizes in re.findall(
            r'memref\.reinterpret_cast %arg(\d+) to offset: \[[^\]]*\], sizes: \[([^\]]*)\]',
            text):
        views.setdefault(int(arg), set()).add(len(split_top_level(sizes)))
    direct = {int(a) for a in re.findall(
        r'(?:affine|memref)\.(?:load|store)\s+(?:%[\w.#]+,\s*)?%arg(\d+)\[', text)}
    return views, direct


HARNESS = r'''// Generated by examples/pom2k/generate_benchmarks.py. Do not edit; rerun the
// generator. Differential CPU (OpenMP) test for @@KERNEL@@: the pipeline output
// without the custom fusion pass (old) and with it (new) run on identical
// inputs; every array is compared bitwise and both variants are timed.
#include <sys/mman.h>
#include <unistd.h>

#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

extern "C" {
@@GLOBAL_DEFS@@
void @@KERNEL@@_old(@@PARAMS@@);
void @@KERNEL@@_new(@@PARAMS@@);
int omp_get_max_threads(void);
}

namespace {

struct Config {
  long im = 1024, jm = 1024, kb = 20;
  int samples = 20;
};

Config gConfig;

enum class Elem { F32, I32 };
enum class Extent { E2D, E3D };

struct ArgSpec {
  const char *name;
  Elem elem;
  Extent extent;
  uint64_t seed;
  bool selector;  // i32 selector: every element holds `selectorValue`
  int32_t selectorValue;
};

const ArgSpec kArgs[] = {
@@ARG_SPECS@@
};
constexpr int kNumArgs = sizeof(kArgs) / sizeof(kArgs[0]);

uint64_t mix(uint64_t x) {
  x += 0x9e3779b97f4a7c15ULL;
  x = (x ^ (x >> 30)) * 0xbf58476d1ce4e5b9ULL;
  x = (x ^ (x >> 27)) * 0x94d049bb133111ebULL;
  return x ^ (x >> 31);
}

// Deterministic value in [0.5, 1.5).
float unitValue(uint64_t seed, uint64_t index) {
  return 0.5f + static_cast<float>(mix(seed ^ mix(index)) >> 40) *
                    (1.0f / 16777216.0f);
}

// The array ends right before a PROT_NONE page, so an access past the end
// faults instead of silently reading or corrupting other memory.
struct GuardedArray {
  void *map = nullptr;
  size_t mapLen = 0;
  void *data = nullptr;
  size_t count = 0;

  GuardedArray() = default;
  GuardedArray(const GuardedArray &) = delete;
  GuardedArray &operator=(const GuardedArray &) = delete;
  GuardedArray(GuardedArray &&o) noexcept { *this = std::move(o); }
  GuardedArray &operator=(GuardedArray &&o) noexcept {
    std::swap(map, o.map);
    std::swap(mapLen, o.mapLen);
    std::swap(data, o.data);
    std::swap(count, o.count);
    return *this;
  }
  ~GuardedArray() {
    if (map)
      munmap(map, mapLen);
  }

  void allocate(size_t n) {
    const size_t page = static_cast<size_t>(sysconf(_SC_PAGESIZE));
    const size_t bytes = n * 4;
    const size_t dataPages = (bytes + page - 1) / page;
    mapLen = (dataPages + 1) * page;
    map = mmap(nullptr, mapLen, PROT_READ | PROT_WRITE,
               MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    if (map == MAP_FAILED) {
      std::perror("mmap");
      std::exit(2);
    }
    char *guard = static_cast<char *>(map) + dataPages * page;
    if (mprotect(guard, page, PROT_NONE) != 0) {
      std::perror("mprotect");
      std::exit(2);
    }
    data = guard - bytes;
    count = n;
  }
};

size_t extentCount(const Config &cfg, Extent e) {
  size_t n2 = static_cast<size_t>(cfg.im) * static_cast<size_t>(cfg.jm);
  return e == Extent::E3D ? n2 * static_cast<size_t>(cfg.kb) : n2;
}

void fill(GuardedArray &a, const ArgSpec &spec) {
  const long long n = static_cast<long long>(a.count);
  if (spec.elem == Elem::I32) {
    int32_t *p = static_cast<int32_t *>(a.data);
#pragma omp parallel for
    for (long long i = 0; i < n; ++i)
      p[i] = spec.selectorValue;
    return;
  }
  float *p = static_cast<float *>(a.data);
#pragma omp parallel for
  for (long long i = 0; i < n; ++i)
    p[i] = unitValue(spec.seed, static_cast<uint64_t>(i));
}

uint64_t contentHash(const GuardedArray &a) {
  const uint32_t *p = static_cast<const uint32_t *>(a.data);
  const long long n = static_cast<long long>(a.count);
  uint64_t h = 0;
#pragma omp parallel for reduction(^ : h)
  for (long long i = 0; i < n; ++i)
    h ^= mix((static_cast<uint64_t>(i) << 32) ^ p[i]);
  return h;
}

void setGlobals(const Config &cfg) {
@@GLOBAL_INIT@@
}

void printGlobals() {
@@GLOBAL_PRINT@@
}

void callKernel(bool newVariant, std::vector<GuardedArray> &b) {
  setGlobals(gConfig);
  if (newVariant)
    @@KERNEL@@_new(@@CALL_ARGS@@);
  else
    @@KERNEL@@_old(@@CALL_ARGS@@);
}

std::vector<GuardedArray> allocateSet(const Config &cfg) {
  std::vector<GuardedArray> set(kNumArgs);
  for (int i = 0; i < kNumArgs; ++i) {
    size_t n = kArgs[i].selector ? 1 : extentCount(cfg, kArgs[i].extent);
    set[i].allocate(n);
    fill(set[i], kArgs[i]);
  }
  return set;
}

double elapsedMs(std::chrono::steady_clock::time_point a,
                 std::chrono::steady_clock::time_point b) {
  return std::chrono::duration<double, std::milli>(b - a).count();
}

bool parseArgs(int argc, char **argv, Config &cfg) {
  for (int i = 1; i < argc; ++i) {
    std::string arg = argv[i];
    if (arg == "--size" && i + 1 < argc) {
      if (std::sscanf(argv[++i], "%ldx%ldx%ld", &cfg.im, &cfg.jm, &cfg.kb) != 3 ||
          cfg.im < 3 || cfg.jm < 3 || cfg.kb < 3) {
        std::fprintf(stderr, "invalid --size '%s' (expected IMxJMxKB, each >= 3)\n", argv[i]);
        return false;
      }
    } else if (arg == "--samples" && i + 1 < argc) {
      cfg.samples = std::atoi(argv[++i]);
      if (cfg.samples < 1) {
        std::fprintf(stderr, "invalid --samples\n");
        return false;
      }
    } else {
      std::fprintf(stderr, "usage: %s [--size IMxJMxKB] [--samples N]\n", argv[0]);
      return false;
    }
  }
  return true;
}

}  // namespace

int main(int argc, char **argv) {
  if (!parseArgs(argc, argv, gConfig))
    return 2;
  const Config &cfg = gConfig;
  setGlobals(cfg);

  std::printf("kernel: @@KERNEL@@\ntarget: cpu_parallel\n");
  std::printf("size: im=%ld jm=%ld kb=%ld\nsamples: %d\nthreads: %d\n", cfg.im,
              cfg.jm, cfg.kb, cfg.samples, omp_get_max_threads());
  printGlobals();

  std::vector<GuardedArray> setOld = allocateSet(cfg);
  std::vector<GuardedArray> setNew = allocateSet(cfg);
  std::vector<uint64_t> initialHash(kNumArgs);
  for (int i = 0; i < kNumArgs; ++i)
    initialHash[i] = contentHash(setOld[i]);

  // Correctness run on fresh inputs.
  callKernel(false, setOld);
  callKernel(true, setNew);

  std::vector<bool> written(kNumArgs, false);
  int mismatchedArrays = 0;
  std::printf("\n%-4s %-12s %-4s %-4s %12s %12s %12s %12s %s\n", "arg", "name",
              "type", "ext", "elements", "mismatches", "max_abs", "max_rel",
              "written");
  for (int i = 0; i < kNumArgs; ++i) {
    const ArgSpec &s = kArgs[i];
    const uint32_t *po = static_cast<const uint32_t *>(setOld[i].data);
    const uint32_t *pn = static_cast<const uint32_t *>(setNew[i].data);
    size_t mismatches = 0;
    double maxAbs = 0.0, maxRel = 0.0;
    for (size_t k = 0; k < setOld[i].count; ++k) {
      if (po[k] == pn[k])
        continue;
      ++mismatches;
      if (s.elem == Elem::F32) {
        float a, b;
        std::memcpy(&a, &po[k], 4);
        std::memcpy(&b, &pn[k], 4);
        if (std::isfinite(a) && std::isfinite(b)) {
          double d = std::fabs(static_cast<double>(a) - b);
          maxAbs = std::max(maxAbs, d);
          double m = std::max(std::fabs(static_cast<double>(a)), std::fabs(static_cast<double>(b)));
          if (m > 0)
            maxRel = std::max(maxRel, d / m);
        }
      }
    }
    written[i] = contentHash(setOld[i]) != initialHash[i] ||
                 contentHash(setNew[i]) != initialHash[i];
    if (mismatches)
      ++mismatchedArrays;
    std::printf("%-4d %-12s %-4s %-4s %12zu %12zu %12.4g %12.4g %s\n", i, s.name,
                s.elem == Elem::F32 ? "f32" : "i32",
                s.selector ? "sel" : (s.extent == Extent::E3D ? "3D" : "2D"),
                setOld[i].count, mismatches, maxAbs, maxRel,
                written[i] ? "yes" : "no");
  }
  const bool pass = mismatchedArrays == 0;
  std::printf("\nresult: %s (%d of %d arrays differ)\n", pass ? "PASS" : "FAIL",
              mismatchedArrays, kNumArgs);

  // Timing: written arrays are refilled before every call, inputs stay as is.
  // One untimed warm-up call per variant; the variant that runs first
  // alternates between samples so neither one always gets the warmer state.
  auto timedCall = [&](bool useNew) {
    std::vector<GuardedArray> &set = useNew ? setNew : setOld;
    for (int i = 0; i < kNumArgs; ++i)
      if (written[i])
        fill(set[i], kArgs[i]);
    auto t0 = std::chrono::steady_clock::now();
    callKernel(useNew, set);
    auto t1 = std::chrono::steady_clock::now();
    return elapsedMs(t0, t1);
  };
  timedCall(false);
  timedCall(true);
  std::vector<double> tOld, tNew;
  for (int s = 0; s < cfg.samples; ++s) {
    const bool newFirst = s % 2 == 1;
    for (bool useNew : {newFirst, !newFirst})
      (useNew ? tNew : tOld).push_back(timedCall(useNew));
  }
  auto avg = [](const std::vector<double> &v) {
    double sum = 0;
    for (double x : v)
      sum += x;
    return sum / static_cast<double>(v.size());
  };
  auto minOf = [](const std::vector<double> &v) {
    return *std::min_element(v.begin(), v.end());
  };
  auto median = [](std::vector<double> v) {
    std::sort(v.begin(), v.end());
    size_t n = v.size();
    return n % 2 ? v[n / 2] : 0.5 * (v[n / 2 - 1] + v[n / 2]);
  };
  const double oldMed = median(tOld), newMed = median(tNew);
  const double speedup = newMed > 0 ? oldMed / newMed : 0.0;
  std::printf("time_old_ms: median %.3f avg %.3f min %.3f\n", oldMed, avg(tOld),
              minOf(tOld));
  std::printf("time_new_ms: median %.3f avg %.3f min %.3f\n", newMed, avg(tNew),
              minOf(tNew));
  std::printf("speedup_new_vs_old (median): %.3f\n", speedup);
  std::printf("SUMMARY kernel=@@KERNEL@@ status=%s mismatched_arrays=%d "
              "arrays=%d old_median_ms=%.3f new_median_ms=%.3f speedup=%.3f\n",
              pass ? "PASS" : "FAIL", mismatchedArrays, kNumArgs, oldMed,
              newMed, speedup);
  return pass ? 0 : 1;
}
'''

WRAPPER = '''#!/usr/bin/env bash
# Generated by examples/pom2k/generate_benchmarks.py. Do not edit; rerun the
# generator. Usage: run_diff_benchmark.sh --target cpu_parallel [--size IMxJMxKB] [--samples N]
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KERNEL="@@KERNEL@@" KERNEL_DIR="$SCRIPT_DIR" exec "$SCRIPT_DIR/../lib/run_diff_kernel.sh" "$@"
'''


def generate(kernel):
    old_path = COMPARE_DIR / "old" / f"{kernel}.mlir"
    new_path = COMPARE_DIR / "new" / f"{kernel}.mlir"
    for p in (old_path, new_path):
        if not p.is_file():
            raise FileNotFoundError(f"{kernel}: missing {p}")
    old_text, new_text = old_path.read_text(), new_path.read_text()
    args = parse_signature(old_text, kernel)
    new_args = parse_signature(new_text, kernel)
    if args is None and new_args is None:
        return "no-function"
    if args != new_args:
        raise ValueError(f"{kernel}: old and new signatures differ")

    views, direct = {}, set()
    for text in (old_text, new_text):
        v, d = three_d_args(text)
        for k, ranks in v.items():
            views.setdefault(k, set()).update(ranks)
        direct |= d

    globals_ = parse_globals(old_text)
    globals_.update(parse_globals(new_text))

    specs = []
    for a in args:
        if a["elem"] == "i32":
            if a["name"] not in SELECTOR_ARRAYS:
                raise ValueError(f"{kernel}: no value configured for i32 array '{a['name']}'")
            specs.append(f'    {{"{a["name"]}", Elem::I32, Extent::E2D, 0ULL, true, '
                         f'{SELECTOR_ARRAYS[a["name"]]}}},')
            continue
        idx = a["index"]
        is3d = idx in direct or idx not in views or 3 in views[idx]
        specs.append(f'    {{"{a["name"]}", Elem::F32, Extent::{"E3D" if is3d else "E2D"}, '
                     f'0x{seed_of(kernel, a["name"], str(idx)):016x}ULL, false, 0}},')

    defs, init, prints = [], [], []
    for name in sorted(globals_):
        elem = globals_[name]
        if elem == "i32":
            defs.append(f"int {name}[1];")
            if name in SIZE_INT_GLOBALS:
                init.append(f"  {name}[0] = static_cast<int>({SIZE_INT_GLOBALS[name]});")
            elif name in FIXED_INT_GLOBALS:
                init.append(f"  {name}[0] = {FIXED_INT_GLOBALS[name]};")
            else:
                raise ValueError(f"{kernel}: no value configured for i32 global '{name}'")
            prints.append(f'  std::printf("global {name} = %d\\n", {name}[0]);')
        else:
            defs.append(f"float {name}[1];")
            init.append(f"  {name}[0] = unitValue(0x{seed_of('global', name):016x}ULL, 0);")
            prints.append(f'  std::printf("global {name} = %.9g\\n", {name}[0]);')

    params = ", ".join(
        f"void *a{i}_alloc, void *a{i}_aligned, int64_t a{i}_offset, "
        f"int64_t a{i}_size, int64_t a{i}_stride" for i in range(len(args)))
    call_args = (",\n        ".join(
        f"b[{i}].data, b[{i}].data, 0, static_cast<int64_t>(b[{i}].count), 1"
        for i in range(len(args))))
    harness = (HARNESS
               .replace("@@KERNEL@@", kernel)
               .replace("@@GLOBAL_DEFS@@", "\n".join(defs) or "// no globals")
               .replace("@@PARAMS@@", params)
               .replace("@@ARG_SPECS@@", "\n".join(specs))
               .replace("@@GLOBAL_INIT@@", "\n".join(init) or "  (void)cfg;")
               .replace("@@GLOBAL_PRINT@@", "\n".join(prints))
               .replace("@@CALL_ARGS@@", call_args))

    out_dir = kernel_dir(kernel)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "diff_cpu_parallel.cpp").write_text(harness)
    wrapper = out_dir / "run_diff_benchmark.sh"
    wrapper.write_text(WRAPPER.replace("@@KERNEL@@", kernel))
    wrapper.chmod(0o755)
    return str(out_dir.relative_to(PROJECT_ROOT))


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("kernels", nargs="+", help="kernel names, e.g. ext_profu_")
    opts = parser.parse_args()
    failed = False
    for kernel in opts.kernels:
        try:
            print(f"{kernel}: {generate(kernel)}")
        except (ValueError, FileNotFoundError) as e:
            print(f"{kernel}: ERROR {e}", file=sys.stderr)
            failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
