def kernel_dir(kernel):
    if kernel in DIR_OVERRIDES:
        return SCRIPT_DIR / DIR_OVERRIDES[kernel]
    name = kernel[len("ext_"):] if kernel.startswith("ext_") else kernel
    return SCRIPT_DIR / ("pom2k_" + name.rstrip("_"))


def seed_of(*parts):
    return int.from_bytes(hashlib.sha256("/".join(parts).encode()).digest()[:8],
                          "little")


def split_top_level(text):
    """Splits on commas that are not nested in (), <>, {}, [] or quotes."""
    parts, depth, cur, quoted = [], 0, [], False
    for ch in text:
        if ch == '"':
            quoted = not quoted
        elif not quoted:
            if ch in "(<{[":
                depth += 1
            elif ch in ")>}]":
                depth -= 1
            elif ch == "," and depth == 0:
                parts.append("".join(cur))
                cur = []
                continue
        cur.append(ch)
    if "".join(cur).strip():
        parts.append("".join(cur))
    return parts


def parse_signature(text, kernel):
    start = text.find(f"func.func @{kernel}(")
    if start < 0:
        return None
    i = text.index("(", start) + 1
    depth, j = 1, i
    while depth:
        if text[j] == "(":
            depth += 1
        elif text[j] == ")":
            depth -= 1
        j += 1
    args = []
    for raw in split_top_level(text[i:j - 1]):
        m = re.match(r'\s*%arg(\d+):\s*memref<\?x(f32|i32)>', raw)
        if not m:
            raise ValueError(f"{kernel}: unsupported argument '{raw.strip()}'")
        name = re.search(r'polygeist\.name = "(\w+)"', raw)
        args.append({"index": int(m.group(1)), "elem": m.group(2),
                     "name": name.group(1) if name else f"arg{m.group(1)}"})
    return args


def parse_globals(text):
    found = {}
    for name, elem in re.findall(
            r'memref\.global (?:"private" )?(?:constant )?@(\w+) : memref<1x(f32|i32)>',
            text):
        found[name] = elem
    return found


def three_d_args(text):
    """Arguments that need im*jm*kb elements: accessed through a rank-3 view,
    accessed directly, or never through a view. Rank-2-only arguments get
    im*jm; the harness guard pages catch an access past that."""
    views = {}
    for arg, sizes in re.findall(
            r'memref\.reinterpret_cast %arg(\d+) to offset: \[[^\]]*\], sizes: \[([^\]]*)\]',
            text):
        views.setdefault(int(arg), set()).add(len(split_top_level(sizes)))
    direct = {int(a) for a in re.findall(
        r'(?:affine|memref)\.(?:load|store)\s+(?:%[\w.#]+,\s*)?%arg(\d+)\[', text)}
    return views, direct


